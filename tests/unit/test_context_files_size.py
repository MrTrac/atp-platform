"""Guard: the AI-context files that every chat loads must stay well under 50,000 bytes (G-CTXBLOAT-1).

`CLAUDE.md`, `AGENTS.md`, `.cursorrules`, `.github/copilot-instructions.md` and `AI_OS_CONTEXT.md` are generated by `aios sync repo ATP` (a managed block) and loaded into the
context of every chat. The rule says < 50,000 bytes. On 15/10/2026 a refresh took `CLAUDE.md` from 44,708 to 50,210 bytes and was only noticed by hand: the generator copies the
FIRST 80 LINES of `AI_NEXT_STEP.md` into the block (`aios_excerpt_file "$src" 80` in `30_RUNTIME/generators/generate_context.sh`), so a few long paragraphs near the top of that
file are enough. The check below turns the rule into a red test with a margin, so the problem shows up on the commit that causes it.

The limit is in BYTES (not characters: Vietnamese text is multi-byte, and a character count under-reports it by ~2 %).

If this fails: shorten the first 80 lines of `~/AI_OS/20_PROJECTS/ATP/AI_NEXT_STEP.md` (move detail to CHANGELOG / the ledger), commit it in AI_OS, then `aios sync repo ATP --apply`.
"""

from __future__ import annotations

import tempfile
import unittest
from pathlib import Path

_ROOT = Path(__file__).resolve().parents[2]
CONTEXT_FILES = ("CLAUDE.md", "AGENTS.md", ".cursorrules", ".github/copilot-instructions.md", "AI_OS_CONTEXT.md")
HARD_LIMIT = 50_000   # G-CTXBLOAT-1
WARN_AT = 49_000      # fail before the hard limit so there is room to fix it


def oversize(paths: list[Path], limit: int) -> list[tuple[str, int]]:
    """(name, bytes) of every file at or above `limit` bytes."""
    return [(p.name, p.stat().st_size) for p in paths if p.stat().st_size >= limit]


class TestContextFilesSize(unittest.TestCase):
    def test_every_context_file_exists(self) -> None:
        missing = [f for f in CONTEXT_FILES if not (_ROOT / f).is_file()]
        self.assertEqual(missing, [], f"AI-context files gone: {missing} (the list in this test must follow the generator)")

    def test_context_files_stay_under_the_warning_limit(self) -> None:
        sizes = {f: (_ROOT / f).stat().st_size for f in CONTEXT_FILES if (_ROOT / f).is_file()}
        too_big = {f: n for f, n in sizes.items() if n >= WARN_AT}
        self.assertEqual(
            too_big, {},
            f"context files at or above {WARN_AT} bytes (hard limit {HARD_LIMIT}, G-CTXBLOAT-1): {too_big}. "
            f"The generator copies the first 80 lines of AI_OS/20_PROJECTS/ATP/AI_NEXT_STEP.md: shorten them, commit in AI_OS, `aios sync repo ATP --apply`. All sizes: {sizes}",
        )

    def test_the_check_counts_bytes_not_characters(self) -> None:
        """The same text is smaller in characters than in bytes when it is Vietnamese; the guard must use bytes."""
        with tempfile.TemporaryDirectory() as d:
            f = Path(d) / "vi.md"
            f.write_text("ế" * 16_400, encoding="utf-8")  # 16,400 characters, 49,200 bytes
            self.assertLess(len(f.read_text(encoding="utf-8")), WARN_AT)
            self.assertEqual(oversize([f], WARN_AT), [("vi.md", 49_200)])

    def test_the_check_flags_a_file_at_the_limit_and_only_then(self) -> None:
        """Seeded defects: exactly at the limit is flagged, one byte under is not; a clean set is silent."""
        with tempfile.TemporaryDirectory() as d:
            at, under, small = (Path(d) / n for n in ("at.md", "under.md", "small.md"))
            at.write_bytes(b"x" * WARN_AT)
            under.write_bytes(b"x" * (WARN_AT - 1))
            small.write_bytes(b"x" * 100)
            self.assertEqual(oversize([at, under, small], WARN_AT), [("at.md", WARN_AT)])
            self.assertEqual(oversize([under, small], WARN_AT), [])

    def test_the_warning_limit_is_below_the_hard_limit_with_room_to_fix(self) -> None:
        self.assertLess(WARN_AT, HARD_LIMIT)
        self.assertGreaterEqual(HARD_LIMIT - WARN_AT, 500)


if __name__ == "__main__":
    unittest.main()
